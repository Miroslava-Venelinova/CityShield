// ─── src/components/leafletWebView.ts ────────────────────────────────────────
// Shared, hardened setup for the two Leaflet-in-a-WebView maps (AlertMap and
// LocationPickerMap).
//
// Both render inside a `javaScriptEnabled` WebView that holds a postMessage
// bridge into the app, and AlertMap additionally renders scraped,
// LLM-processed third-party data. That combination is why the settings below
// are deliberately restrictive rather than the react-native-webview defaults.

import type {WebViewProps} from 'react-native-webview';
import {API_BASE_URL} from '../config';
import {version as APP_VERSION} from '../../package.json';
// Generated by `postinstall` from the pinned `leaflet` package, SHA-512 checked
// (scripts/vendor-leaflet.mjs). Missing file = failed bundle, never a blank map.
import {LEAFLET_CSS, LEAFLET_JS} from '../vendor/leaflet.generated';

/**
 * `<head>` contents: viewport, a locked-down CSP, and Leaflet itself, inline.
 *
 * Leaflet ships inside the APK rather than coming from a CDN. Loaded from
 * unpkg.com, the map was blank whenever unpkg was down or blocked, and unpkg
 * received every map user's IP address (docs/todo.md §8.2, §9.1). Integrity
 * used to come from SRI on the unpkg tags; it now comes from the pinned hashes
 * the build checks and from the APK signature.
 *
 * `'unsafe-inline'` for script-src is unavoidable: Leaflet and the map
 * bootstrap run as inline scripts and RN's `injectJavaScript` bridge also
 * evaluates inline. The origin allowlist is what carries the value here —
 * `default-src 'none'` means anything not named below cannot load at all, and
 * the only network origin left is the OSM tile server.
 *
 * leaflet.css refers to a few images by relative URL (layer-switcher and
 * default-marker icons). Neither map uses those controls, and against the
 * about:blank document a relative URL resolves to nothing, so nothing is
 * requested.
 */
export const LEAFLET_HEAD = `
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no"/>
<meta http-equiv="Content-Security-Policy" content="
  default-src 'none';
  script-src 'unsafe-inline';
  style-src 'unsafe-inline';
  img-src https://tile.openstreetmap.org https://*.tile.openstreetmap.org data:;
  connect-src 'none';
  form-action 'none';
  base-uri 'none';
  frame-ancestors 'none';
"/>
<style>${LEAFLET_CSS}</style>
<style>
  /* The tile-failure notice (osmTileLayerScript). Above the map panes, out of
     the way of the RN overlay buttons, and transparent to touches so it never
     blocks panning. */
  .cs-tile-notice {
    display: none;
    position: absolute; top: 10px; left: 50%;
    transform: translateX(-50%);
    max-width: calc(100% - 112px);
    z-index: 1000;
    padding: 6px 10px; border-radius: 8px;
    background: rgba(17,24,39,0.88); color: #fff;
    font-size: 12px; line-height: 1.35; text-align: center;
    pointer-events: none;
  }
</style>
<script>${LEAFLET_JS}</script>`;

/**
 * A string as a JavaScript literal that is also safe inside an inline
 * `<script>`: JSON.stringify alone would let a `</script>` end the element.
 */
function jsString(value: string): string {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

/**
 * How long a pass of tiles may stay unfinished before the notice shows anyway.
 * An unreachable network does not always fail fast — a dropped packet can hold
 * an image request open for minutes, and until it errors the map is simply
 * grey. Long enough not to fire on an ordinary slow mobile connection.
 */
const TILE_STALL_MS = 20_000;

/**
 * Page script for the OSM tile layer and its attribution, shared by both maps.
 * Expects the page to have created `map` first.
 *
 * When tiles fail, the map says so (docs/todo.md §9.1). Before this, a tile
 * server that refused us, a blocked network or a dead connection all looked
 * the same: a silent grey rectangle, indistinguishable from "still loading".
 * The notice is per *pass* of tiles: Leaflet fires `loading` when it starts
 * fetching a view and `load` once every tile of it has settled, failed ones
 * included. A pass with any `tileerror` keeps the notice up; the next pass that
 * completes cleanly (a pan, a zoom, reopening the screen) takes it down.
 *
 * There is deliberately no second tile provider to fall back to — that would be
 * a new processor receiving users' IP addresses (docs/compliance.md §5).
 * Failed tiles are not retried on a timer either: hammering a server that is
 * refusing us is how an app gets blocked for good.
 */
export function osmTileLayerScript(noticeText: string): string {
  return `
  var tiles = L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {
    maxZoom: 19,
    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors'
  }).addTo(map);

  (function () {
    var notice = null;
    var failedThisPass = false;
    var stallTimer = null;

    function showNotice() {
      if (!notice) {
        notice = document.createElement('div');
        notice.className = 'cs-tile-notice';
        notice.setAttribute('role', 'status');
        notice.textContent = ${jsString(noticeText)};
        map.getContainer().appendChild(notice);
      }
      notice.style.display = 'block';
    }

    tiles.on('loading', function () {
      failedThisPass = false;
      clearTimeout(stallTimer);
      stallTimer = setTimeout(showNotice, ${TILE_STALL_MS});
    });
    tiles.on('tileerror', function () {
      failedThisPass = true;
      showNotice();
    });
    tiles.on('load', function () {
      clearTimeout(stallTimer);
      if (notice && !failedThisPass) { notice.style.display = 'none'; }
    });
  })();`;
}

/**
 * Page-side half of the "map inside a ScrollView" fix, injected into both map
 * documents (they define `post` before including it).
 *
 * The problem: on Android the parent ScrollView claims a vertical drag that
 * started inside the WebView, so trying to pan the map scrolled the whole
 * Home screen instead. The RN side reacts by disabling the ScrollView for the
 * duration of the gesture — but it can only put scrolling *back* once it knows
 * the touch is over, and a native child swallows the touch-end that the
 * responder system would otherwise report. So the page tells us directly.
 *
 * `touchcancel` matters as much as `touchend`: it is what fires if the
 * platform tears the gesture away mid-pan, and without it the ScrollView would
 * stay disabled for good.
 */
export const MAP_GESTURE_SCRIPT = `
  (function () {
    var active = false;
    function start() {
      if (active) { return; }
      active = true;
      post({ type: 'gestureStart' });
    }
    function end(e) {
      // Multi-touch pinch: only release once the last finger is up.
      if (!active || (e && e.touches && e.touches.length > 0)) { return; }
      active = false;
      post({ type: 'gestureEnd' });
    }
    document.addEventListener('touchstart', start, { passive: true });
    document.addEventListener('touchend', end, { passive: true });
    document.addEventListener('touchcancel', end, { passive: true });
  })();`;

/**
 * Security props shared by both maps.
 *
 * Neither page ever legitimately navigates: they are fixed local documents.
 * The previous `originWhitelist={['*']}` with no load guard meant any link —
 * including one reachable through injected content — could navigate the
 * WebView to an arbitrary origin while keeping the RN bridge attached.
 */
export const hardenedWebViewProps: Partial<WebViewProps> = {
  originWhitelist: ['about:blank'],
  onShouldStartLoadWithRequest: req => {
    // Only the initial in-place load of our own HTML is permitted. Note that
    // react-native-webview checks `originWhitelist` *before* calling this: a
    // URL outside it never reaches here and is handed to Linking.openURL
    // instead (13.x, WebViewShared.tsx). That is what happens to the OSM
    // attribution link — it opens in the system browser, never inside this
    // privileged WebView. Read from the library source; not yet confirmed on a
    // device.
    const allowed =
      req.url === 'about:blank' || req.url.startsWith('data:text/html');
    if (!allowed) {
      console.warn(`Map WebView: blocked navigation to ${req.url}`);
    }
    return allowed;
  },
  javaScriptEnabled: true,
  // OSM's tile policy requires "a distinct, stable User-Agent naming your
  // app", and blocks library defaults (docs/legal.md §7). This is appended to
  // the WebView's own agent, so it reaches every tile request without
  // pretending to be anything else, and names a page with our contact.
  //
  // Tiles carry no Referer: the document is loaded as about:blank. The policy
  // accepts that from apps ("Native apps usually do not have a referer, this is
  // ok") as long as the agent names the app. A Referer could be had by giving
  // `source` a `baseUrl` on the Worker's origin, but that hands a page full of
  // third-party alert text the API's origin, for nothing the policy asks for.
  applicationNameForUserAgent: `CityShield/${APP_VERSION} (+${API_BASE_URL.replace(/\/+$/, '')}/privacy)`,
  // Neither map persists anything, so storage and filesystem reach are pure
  // attack surface here.
  domStorageEnabled: false,
  allowFileAccess: false,
  allowFileAccessFromFileURLs: false,
  allowUniversalAccessFromFileURLs: false,
  javaScriptCanOpenWindowsAutomatically: false,
  // Tiles are HTTPS (and Leaflet is inline); refuse any downgrade.
  mixedContentMode: 'never',
  setSupportMultipleWindows: false,
  overScrollMode: 'never',
  // Android: let the WebView win the drag against an enclosing ScrollView
  // instead of forwarding it upward the moment it moves vertically.
  nestedScrollEnabled: true,
};

/**
 * Guards a number before it is interpolated into generated page JavaScript.
 * Rejects NaN/Infinity, which would otherwise reach `setView` and leave the
 * map blank with no error.
 */
export function safeCoord(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}
